// manual.js - 网站使用手册，供弹窗和本地 AI 共用

const SITE_MANUAL_MARKDOWN = `
## 超时空辉夜姬使用手册

### 1. 练习模式
- **刷题模式**：正常做题，提交后显示正确/错误、答案、全站统计和题解评论。
- **错题重做**：只抽取错题本里的题目，答对后会从错题本移除。
- **答案速背**：不做交互答题，直接按题目列表查看答案，适合考前快速过一遍。

### 2. 题型与抽题
- 支持单选题、多选题、填空题、简答题，也可以选择全部题型。
- 出题顺序支持随机或按文件顺序。
- 本轮题数控制总抽题量。
- 用户偏好里可以设置：单选选完自动提交、选项乱序、答对后自动下一题、单选题在前多选题在后。
- 如果填写随机单选数、多选数、填空数、简答数，会按各题型数量抽题；都为 0 时按“本轮题数”抽题。

### 3. 专题选择
- 首页右侧是专题树：课程名称为大专题，展开后可选择章节和小节。
- 勾选大专题会包含其下级专题；也可以只勾选某个小专题。
- 可以搜索课程、专题和标签。
- “全选/反选”用于快速切换当前专题选择。

### 4. 刷题页操作
- 提交答案后会显示正确答案、你的作答、全站正确率和本题题解/评论。
- “直接看答案”会显示答案，但通常会按看答案记录。
- “重新作答”用于错题跳回后再次作答。
- “题号列表”可以查看本轮每题状态：灰色未做、绿色正确、红色错误、黄色看过答案。
- 电脑端快捷键：1-4 选择 A-D，5 直接看答案，空格用于提交/下一题/看答案。

### 5. 历史记录
- 首页“历史记录”会列出最近刷题轮次。
- 未完成的记录可以继续刷。
- 已完成或未完成记录都可以查看题号详情。
- 单机模式历史只保存在当前设备；同步模式历史跟随同步码。

### 6. 同步模式与单机模式
- **同步模式**：使用同步码和邀请码，进度、错题等会同步到云端。
- **单机模式**：不需要同步码，进度只保存在当前设备。
- 题解和评论是全站共享内容；单机模式不能发布或编辑云端题解评论。

### 7. 题解与评论
- 每道题提交或看答案后，才显示题解和评论。
- 题解支持 Markdown。
- 评论可以记录易错点、口诀、解释或补充材料。

### 8. 题库管理
- 题库管理需要管理密码。
- 可新增、编辑、删除题目。
- 支持导入 JSON、Word、TXT 题库，也支持导出题库。
- 题目修改不会直接改原始题库，而是保存为题库编辑层，方便同步和恢复。
- 添加图片时可以在题干、选项或参考答案中使用 Markdown 图片语法：![说明](图片地址)。

### 9. 专题管理
- 专题管理需要管理密码。
- 可新建专题/子专题、移动专题、提升子专题、删除专题及其题目。
- 空专题也能显示在专题树中，方便先建目录再补题。

### 10. AI 问答
- 首页右下角头像按钮“问 AI”会打开本机 AI 对话框。
- 默认使用本机 Ollama；如果配置了公网 AI API，则会调用公网服务，方便多人使用。
- 支持流式输出、深度思考、Markdown 和 LaTeX。
- 刷题页的“问 AI”会自动带入当前题干、选项、答案和题图。
- 如果题目有图片，会自动发送给支持视觉输入的 Ollama 模型。
- 深度思考会更慢，但回答更充分。
- 公网 API 可在浏览器控制台配置：localStorage.setItem('quiz_public_ai_endpoint_v1', 'https://你的域名/api/chat')。

### 11. Markdown 与 LaTeX
- Markdown 支持加粗、列表、代码块、链接、图片等常见写法。
- 行内公式写作 $a^2+b^2=c^2$。
- 独立公式写作 $$E=mc^2$$。
`.trim();

function siteManualMarkdown() {
  return SITE_MANUAL_MARKDOWN;
}

function siteManualHtml() {
  return renderMarkdown(siteManualMarkdown());
}

function siteManualForAi() {
  return [
    '下面是本网站的使用手册。用户询问网站功能、按钮、模式、同步、题库管理、AI 问答、Markdown/LaTeX 时，优先依据这份手册回答。',
    siteManualMarkdown()
  ].join('\n\n');
}

